#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CliCommandPolicy {
    Local,
    Observe,
    Activate,
    Resolve,
    Stop,
    Run,
    Submit,
    Stream,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CliOptionKind {
    Value,
    Flag,
    Repeatable,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CliOptionSpec {
    pub name: &'static str,
    pub kind: CliOptionKind,
    pub required: bool,
    pub root_path: bool,
    pub allowed_values: &'static [&'static str],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CliCommandSpec {
    pub command: &'static str,
    pub path: &'static [&'static str],
    pub policy: CliCommandPolicy,
    pub scope: &'static str,
    pub risk: &'static str,
    pub requires: &'static str,
    pub writes: &'static str,
    pub input: &'static str,
    pub output: &'static str,
    pub minimum_positionals: usize,
    pub maximum_positionals: usize,
    pub root_positional: Option<usize>,
    pub options: &'static [CliOptionSpec],
    pub errors: &'static [&'static str],
}

